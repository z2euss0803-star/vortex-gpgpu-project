"""Auditable pointer-prologue-only extraction from immutable V5 mathematics."""
import hashlib,pathlib,re,sys
ROOT=pathlib.Path(__file__).resolve().parents[2]
SOURCE=ROOT/'vendor/hunet/v5/include/hunet_ops_baseline.h'
DEST=ROOT/'device/vxnn/hunet_scalar_math.h'
SHA='152d00a0674627918f4181a6608872122f3d64ab240781715b61ba3e103cd54a'
def generated():
 raw=SOURCE.read_bytes();assert hashlib.sha256(raw).hexdigest()==SHA
 text=raw.decode().replace('\r\n','\n');body=text.split('    switch(j->op) {\n',1)[1].rsplit('    }\n}',1)[0]
 # Python3.6 rejects zero-width re.split; positions preserve every source byte.
 starts=[m.start() for m in re.finditer(r'^    case ',body,flags=re.M)]+[len(body)]
 chunks=[body[starts[i]:starts[i+1]] for i in range(len(starts)-1)]
 allowed={'GN_STATS','GN_APPLY','SIGMOID','ADD','MUL_CHANNEL','COPY','SLICE','CONCAT','GAP','SHIFT'}
 selected=[s for s in chunks if re.match(r'    case HUNET_(\w+):',s).group(1) in allowed]
 assert len(selected)==10
 body=''.join(selected)
 body=body.replace('const float *stats=(const float*)(uintptr_t)j->scratch;','const float *stats=b.stats.data;')
 body=body.replace('const float *gamma=(const float*)(uintptr_t)j->gamma,*beta=(const float*)(uintptr_t)j->beta;','const float *gamma=b.gamma.data,*beta=b.beta.data;')
 assert '(uintptr_t)' not in body and 'HUNET_GELU' not in body
 return ('// Generated by scripts/unified/generate_hunet_scalar.py; do not edit.\n'
  '// Frozen V5 arithmetic SHA256='+SHA+'; only pointer bindings changed.\n'
  '#pragma once\n#include "hunet_ops.h"\n#include "vendor/hunet/v5/include/hunet_math.h"\n'
  'static inline void vxnn_hunet_scalar_math(const HunetJobV1*j,uint32_t t,const VxnnHunetScalarBuffers&b){\n'
  ' const float*x=b.x.data,*w=b.w.data;float*y=b.y.data;\n'
  ' uint32_t hw=j->ih*j->iw,ohw=j->oh*j->ow;\n switch(j->op){\n'+body+' }\n}\n')
if __name__=='__main__':
 value=generated()
 if '--check' in sys.argv:assert DEST.read_bytes()==value.encode(), 'generated scalar source drift'
 else:DEST.write_bytes(value.encode())
 print('U12_TYPED_SCALAR_EXTRACTION_SOURCE_EXACT_NOT_GPU')
