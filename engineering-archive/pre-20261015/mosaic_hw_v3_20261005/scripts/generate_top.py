"""Emit explicit, reviewable port maps from the generated PS wrapper."""
from pathlib import Path
import re,json
r=Path(__file__).resolve().parents[1]
wrapper=r/'build/vivado/gpgpu_soc.srcs/sources_1/bd/ps_bd/hdl/ps_bd_wrapper.v'
ports=re.findall(r'^  (input|output)\s*(\[[^\]]+\])?\s*(\w+);',wrapper.read_text(),re.M)
assert len(ports)>70
axi=[p for p in ports if p[2].startswith(('HP_','HPM_'))]
inv={'input':'output','output':'input'}
out=['`timescale 1ns/1ps','// Generated by scripts/generate_top.py; explicit PS/Vortex boundary.',
     'module gpgpu_subsystem (','  input wire clk, resetn,']
out += ['  '+inv[d]+' wire '+(w+' ' if w else '')+n+(',' if i<len(axi)-1 else '') for i,(d,w,n) in enumerate(axi)]
out += [');','  wire gpu_busy,gpu_reset,dcr_wr_valid,tex_pending,tex_error;','  wire [11:0] dcr_wr_addr;','  wire [31:0] dcr_wr_data;']
lite={'awaddr':40,'awprot':3,'awvalid':1,'awready':1,'wdata':32,'wstrb':4,'wvalid':1,'wready':1,
      'bresp':2,'bvalid':1,'bready':1,'araddr':40,'arprot':3,'arvalid':1,'arready':1,
      'rdata':32,'rresp':2,'rvalid':1,'rready':1}
out += ['  wire '+(f'[{w-1}:0] ' if w>1 else '')+'ctl_'+n+';' for n,w in lite.items()]
maps=['.aclk(clk)','.aresetn(resetn)','.s_axi_awregion(4\'b0)','.s_axi_arregion(4\'b0)']
maps += [f'.s_axi_{n[4:]}({n})' for d,w,n in axi if n.startswith('HPM_') and not n.endswith('user')]
maps += [f'.m_axi_{n}(ctl_{n})' for n in lite]
out += ['  ctrl_axi_converter converter (\n    '+',\n    '.join(maps)+'\n  );']
maps=['.clk(clk)','.resetn(resetn)','.gpu_busy(gpu_busy)','.gpu_reset(gpu_reset)',
      '.tex_pending(tex_pending)','.tex_error(tex_error)',
      '.dcr_wr_valid(dcr_wr_valid)','.dcr_wr_addr(dcr_wr_addr)','.dcr_wr_data(dcr_wr_data)']
maps += [f'.s_axi_{n}(ctl_{n})' for n in lite if not n.endswith('prot')]
maps += [f'.mem_{n}(HP_{n})' for n in ['awvalid','awready','wvalid','wready','wlast','bvalid','bready','bresp','arvalid','arready','rvalid','rready','rlast','rresp']]
out += ['  gpgpu_ctrl ctrl (\n    '+',\n    '.join(maps)+'\n  );']
maps=['.clk(clk)','.reset(gpu_reset)','.busy(gpu_busy)',
      '.tex_pending(tex_pending)','.tex_error(tex_error)',
      '.dcr_wr_valid(dcr_wr_valid)','.dcr_wr_addr(dcr_wr_addr)','.dcr_wr_data(dcr_wr_data)']
for d,w,n in axi:
    if not n.startswith('HP_'):continue
    suffix=n[3:]
    if suffix.endswith('user'):
        out.append(f"  assign {n}=1'b0;");continue
    arr='gpu_'+suffix
    aw='[31:0]' if suffix.endswith('addr') else '[1:0]' if suffix.endswith('lock') else w
    out.append('  wire '+(aw+' ' if aw else '')+arr+' [1];')
    if d=='input':
        expr="{17'd0,"+arr+'[0]}' if suffix.endswith('addr') else arr+'[0][0]' if suffix.endswith('lock') else arr+'[0]'
        out.append(f'  assign {n}={expr};')
    else:out.append(f'  assign {arr}[0]={n};')
    maps.append(f'.m_axi_{suffix}({arr})')
for n in ['awregion','arregion']:
    out.append(f'  wire [3:0] gpu_{n} [1];');maps.append(f'.m_axi_{n}(gpu_{n})')
out += ['  Vortex_axi #(.AXI_DATA_WIDTH(128), .AXI_ADDR_WIDTH(32), .AXI_TID_WIDTH(6), .AXI_NUM_BANKS(1)) gpu (\n    '+',\n    '.join(maps)+'\n  );','endmodule']
(r/'rtl/gpgpu_subsystem.sv').write_text('\n'.join(out)+'\n')
out=['`timescale 1ns/1ps','// Hard PS pins are implicit for Zynq UltraScale+. No external PL I/O.','module top;']
out += ['  wire '+(w+' ' if w else '')+n+';' for d,w,n in ports if n!='axi_clk']
out += ['  ps_bd_wrapper ps (\n    '+',\n    '.join(f'.{n}({"pl_clk0" if n=="axi_clk" else n})' for d,w,n in ports)+'\n  );',
        '  gpgpu_subsystem pl (.clk(pl_clk0), .resetn(axi_resetn[0]),\n    '+',\n    '.join(f'.{n}({n})' for d,w,n in axi)+'\n  );','endmodule']
(r/'rtl/top.sv').write_text('\n'.join(out)+'\n')
(r/'config/ports.json').write_text(json.dumps(axi,indent=2))
print('TOP_GENERATED: real PS wrapper, AXI converter, Vortex_axi')
